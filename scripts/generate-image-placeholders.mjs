import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { clientProjects, projects } from "../src/constants/index.js";

const root = process.cwd();
const output = path.join(root, "src/generated");
await fs.mkdir(output, { recursive: true });

async function writeMap(name, sources) {
  const entries = [];
  for (const src of [...new Set(sources)].sort()) {
    const image = await sharp(path.join(root, "public", src))
      .resize({ width: 20, withoutEnlargement: true })
      .blur(0.8)
      .webp({ quality: 30 })
      .toBuffer();
    entries.push([src, "data:image/webp;base64," + image.toString("base64")]);
  }
  await fs.writeFile(
    path.join(output, name + ".js"),
    "// Generated by scripts/generate-image-placeholders.mjs.\nexport const " +
      name +
      " = " +
      JSON.stringify(Object.fromEntries(entries), null, 2) +
      ";\n",
  );
  console.log(name + ": " + entries.length + " image previews");
}

const directory = await fs.readdir(path.join(root, "public/assets/directory"));
const blog = await fs.readdir(path.join(root, "public/blog-images"));
await writeMap("projectPlaceholders", [
  ...projects.map((project) => project.image),
  ...clientProjects.flatMap((project) => project.images),
  "/images/ritesh-editorial.png",
  "/images/pfp.webp",
]);
await writeMap(
  "directoryPlaceholders",
  directory
    .filter((file) => file.endsWith(".webp"))
    .map((file) => "/assets/directory/" + file),
);
await writeMap(
  "blogPlaceholders",
  blog
    .filter((file) => /\.(jpe?g|png|webp)$/i.test(file))
    .map((file) => "/blog-images/" + file),
);
